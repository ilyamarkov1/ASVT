$MOD51	; This includes 8051 definitions for the Metalink assembler

ORG 0000h

START:
    MOV P2, #0FFh      ; ????????? ?????????
    SETB P3.1          ; P3.1 ??? ????

MAIN:
    JB P3.1, MAIN      ; ????? ??????? ??????

    ACALL DELAY_BTN    ; ???????????

    MOV DPTR, #TABLE
    MOV R0, #05h       ; 5 ????: 9, 7, 5, 3, 1

SHOW_LOOP:
    MOV P2, #0FFh      ; ????? ????????? ????? ?????? ?????
    ACALL DELAY_SHORT

    CLR A
    MOVC A, @A+DPTR
    MOV P2, A          ; ??????? ?????

    ACALL DELAY

    INC DPTR
    DJNZ R0, SHOW_LOOP

    MOV P2, #0FFh      ; ????????? ????????? ????? ??????

WAIT_RELEASE:
    JNB P3.1, WAIT_RELEASE
    ACALL DELAY_BTN

    SJMP MAIN


TABLE:
    DB 090h            ; 9
    DB 0F8h            ; 7
    DB 092h            ; 5
    DB 0B0h            ; 3
    DB 0F9h            ; 1


DELAY:
    MOV R5, #255
D1:
    MOV R6, #255
D2:
    DJNZ R6, D2
    DJNZ R5, D1
    RET


DELAY_SHORT:
    MOV R4, #30
DS1:
    DJNZ R4, DS1
    RET


DELAY_BTN:
    MOV R7, #100
DB1:
    DJNZ R7, DB1
    RET

END